-- ---------------------------------------------------------------------
-- 1. プロフィール（auth.users と 1対1）
-- ---------------------------------------------------------------------
create table public.profiles (
  id                 uuid primary key references auth.users(id) on delete cascade,
  display_name       text check (char_length(display_name) <= 50),
  role               text not null default 'user' check (role in ('user', 'admin')),
  is_banned          boolean not null default false,       -- 荒らし対策：編集禁止
  adult_confirmed_at timestamptz,                           -- 18歳以上の確認日時
  created_at         timestamptz not null default now()
);

-- ---------------------------------------------------------------------
-- 2. 権限判定の関数
-- ---------------------------------------------------------------------
-- 管理者か
create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from profiles where id = auth.uid() and role = 'admin');
$$;

-- 管理者・サービスロール（毎日のまとめ処理）・SQL Editor のどれか
create or replace function public.is_privileged()
returns boolean language sql stable security definer set search_path = public as $$
  select coalesce(auth.role(), '') not in ('anon', 'authenticated') or is_admin();
$$;

-- 編集できる利用者か（ログイン済み・18歳確認済み・編集禁止でない）
create or replace function public.can_edit()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from profiles
    where id = auth.uid() and not is_banned and adult_confirmed_at is not null
  );
$$;

-- ---------------------------------------------------------------------
-- 3. 用語
-- ---------------------------------------------------------------------
create table public.terms (
  id          bigint generated by default as identity primary key,  -- 差し戻しで同じidを復元できるよう by default
  label       text not null check (char_length(btrim(label)) between 1 and 100),
  description text check (char_length(description) <= 2000),
  is_hidden   boolean not null default false,   -- 管理者による非表示
  deleted_at  timestamptz,                      -- 利用者による削除（論理削除）
  created_by  uuid references auth.users(id) on delete set null default auth.uid(),
  created_at  timestamptz not null default now(),
  updated_by  uuid references auth.users(id) on delete set null,
  updated_at  timestamptz not null default now()
);

-- 削除されていない用語の中で名前の重複を禁止（大文字小文字・前後空白を無視）
create unique index terms_label_uniq on public.terms (lower(btrim(label))) where deleted_at is null;

-- ---------------------------------------------------------------------
-- 4. 親子関係（多対多）
-- ---------------------------------------------------------------------
create table public.term_parents (
  child_id   bigint not null references public.terms(id) on delete cascade,
  parent_id  bigint not null references public.terms(id) on delete cascade,
  created_by uuid references auth.users(id) on delete set null default auth.uid(),
  created_at timestamptz not null default now(),
  primary key (child_id, parent_id),
  check (child_id <> parent_id)
);
create index term_parents_parent_idx on public.term_parents (parent_id);

-- ---------------------------------------------------------------------
-- 5. 履歴（トリガーで自動記録。利用者は直接書けない）
-- ---------------------------------------------------------------------
create table public.revisions (
  id          bigint generated always as identity primary key,
  table_name  text not null check (table_name in ('terms', 'term_parents')),
  op          text not null check (op in ('INSERT', 'UPDATE', 'DELETE')),
  term_id     bigint not null,       -- terms: 用語id ／ term_parents: 子のid
  parent_id   bigint,                -- term_parents のときの親id
  old_data    jsonb,
  new_data    jsonb,
  actor       uuid,                  -- 変更した利用者（まとめ処理なら null）
  source      text not null default 'user' check (source in ('user', 'system', 'revert')),
  reverted_at timestamptz,
  reverted_by uuid,
  created_at  timestamptz not null default now()
);
create index revisions_term_idx on public.revisions (term_id, created_at desc);
create index revisions_created_idx on public.revisions (created_at desc);

-- ---------------------------------------------------------------------
-- 6. 通報（荒らし・スパム対策）
-- ---------------------------------------------------------------------
create table public.reports (
  id         bigint generated always as identity primary key,
  term_id    bigint references public.terms(id) on delete cascade,
  reason     text not null check (char_length(reason) between 1 and 1000),
  reporter   uuid references auth.users(id) on delete set null default auth.uid(),
  status     text not null default 'open' check (status in ('open', 'resolved', 'dismissed')),
  created_at timestamptz not null default now()
);

-- =====================================================================
-- トリガー
-- =====================================================================

-- 新規登録時にプロフィールを作成（Google / GitHub の表示名を初期値に）
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into profiles (id, display_name)
  values (
    new.id,
    left(coalesce(new.raw_user_meta_data->>'name', new.raw_user_meta_data->>'user_name'), 50)
  );
  return new;
end $$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- プロフィール：一般利用者は role・is_banned を変えられない。18歳確認は一度だけ記録
create or replace function public.profiles_guard()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if not is_privileged() then
    if new.role is distinct from old.role or new.is_banned is distinct from old.is_banned
       or new.created_at is distinct from old.created_at then
      raise exception 'この項目は変更できません';
    end if;
    if new.adult_confirmed_at is distinct from old.adult_confirmed_at then
      if old.adult_confirmed_at is not null then
        raise exception '18歳以上の確認は取り消せません';
      end if;
      new.adult_confirmed_at := now();
    end if;
  end if;
  return new;
end $$;

create trigger profiles_guard
  before update on public.profiles
  for each row execute function public.profiles_guard();

-- 用語：作成者・更新者の自動設定と、一般利用者が変えてはいけない列の保護
create or replace function public.terms_before_write()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if not is_privileged() then
    if tg_op = 'INSERT' then
      new.created_by := auth.uid();
      new.created_at := now();
      new.is_hidden  := false;
      new.deleted_at := null;
    else
      if new.is_hidden is distinct from old.is_hidden then
        raise exception '非表示の切り替えは管理者のみです';
      end if;
      if new.created_by is distinct from old.created_by or new.created_at is distinct from old.created_at
         or new.id is distinct from old.id then
        raise exception 'この項目は変更できません';
      end if;
    end if;
  end if;
  new.updated_by := auth.uid();
  new.updated_at := now();
  return new;
end $$;

create trigger terms_before_write
  before insert or update on public.terms
  for each row execute function public.terms_before_write();

-- 親子関係：循環（自分の子孫を親にする）を禁止
-- 非表示の用語を経由する循環も防ぐため security definer で全件を見る
create or replace function public.term_parents_prevent_cycle()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if exists (
    with recursive ancestors(id) as (
      select parent_id from term_parents where child_id = new.parent_id
      union
      select tp.parent_id from term_parents tp join ancestors a on tp.child_id = a.id
    )
    select 1 from ancestors where id = new.child_id
  ) then
    raise exception '循環する親子関係は作れません（% → %）', new.child_id, new.parent_id;
  end if;
  if not is_privileged() then
    new.created_by := auth.uid();
    new.created_at := now();
  end if;
  return new;
end $$;

create trigger term_parents_prevent_cycle
  before insert on public.term_parents
  for each row execute function public.term_parents_prevent_cycle();

-- 履歴の記録（terms / term_parents 共通）
create or replace function public.log_revision()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  v_old jsonb;
  v_new jsonb;
  v_row jsonb;
  v_src text;
begin
  if tg_op <> 'INSERT' then v_old := to_jsonb(old); end if;
  if tg_op <> 'DELETE' then v_new := to_jsonb(new); end if;

  -- updated_at / updated_by だけの変化は記録しない
  if tg_op = 'UPDATE'
     and (v_old - 'updated_at' - 'updated_by') = (v_new - 'updated_at' - 'updated_by') then
    return null;
  end if;

  v_row := coalesce(v_new, v_old);
  v_src := coalesce(
    nullif(current_setting('app.source', true), ''),
    case when auth.role() = 'service_role' then 'system' else 'user' end
  );

  insert into revisions (table_name, op, term_id, parent_id, old_data, new_data, actor, source)
  values (
    tg_table_name,
    tg_op,
    case when tg_table_name = 'terms' then (v_row->>'id')::bigint else (v_row->>'child_id')::bigint end,
    case when tg_table_name = 'term_parents' then (v_row->>'parent_id')::bigint end,
    v_old,
    v_new,
    auth.uid(),
    v_src
  );
  return null;
end $$;

create trigger terms_log
  after insert or update or delete on public.terms
  for each row execute function public.log_revision();

create trigger term_parents_log
  after insert or delete on public.term_parents
  for each row execute function public.log_revision();

-- =====================================================================
-- RLS（行単位のアクセス制御）
-- =====================================================================
alter table public.profiles     enable row level security;
alter table public.terms        enable row level security;
alter table public.term_parents enable row level security;
alter table public.revisions    enable row level security;
alter table public.reports      enable row level security;

-- ---- profiles ----
-- 表示名は履歴の表示に使うため誰でも読める
create policy profiles_select on public.profiles
  for select using (true);
-- 自分の行だけ更新できる（role・is_banned はトリガーで保護）。管理者は全員分
create policy profiles_update on public.profiles
  for update using (id = auth.uid() or is_admin())
  with check (id = auth.uid() or is_admin());
-- insert / delete はポリシーなし＝不可（登録時はトリガーが作成）

-- ---- terms ----
-- 誰でも（未ログインでも）表示中の用語を読める。管理者は非表示・削除済みも読める
create policy terms_select on public.terms
  for select using ((not is_hidden and deleted_at is null) or is_admin());
-- 編集できる利用者は追加できる
create policy terms_insert on public.terms
  for insert with check (can_edit());
-- 編集できる利用者は表示中の用語を更新できる（削除は RPC soft_delete_term を使う）
create policy terms_update on public.terms
  for update using (can_edit() and not is_hidden and deleted_at is null)
  with check (can_edit() and not is_hidden and deleted_at is null);
-- 管理者はすべての操作が可能（完全削除を含む）
create policy terms_admin on public.terms
  for all using (is_admin()) with check (is_admin());

-- ---- term_parents ----
-- 両端の用語が見えている関係だけ読める（terms の RLS がそのまま効く）
create policy term_parents_select on public.term_parents
  for select using (
    exists (select 1 from public.terms t where t.id = child_id)
    and exists (select 1 from public.terms t where t.id = parent_id)
  );
-- 編集できる利用者は、表示中の用語どうしを結べる
create policy term_parents_insert on public.term_parents
  for insert with check (
    can_edit()
    and exists (select 1 from public.terms t where t.id = child_id  and not t.is_hidden and t.deleted_at is null)
    and exists (select 1 from public.terms t where t.id = parent_id and not t.is_hidden and t.deleted_at is null)
  );
-- 編集できる利用者は関係を外せる（履歴に残り、管理者が戻せる）
create policy term_parents_delete on public.term_parents
  for delete using (can_edit());
create policy term_parents_admin on public.term_parents
  for all using (is_admin()) with check (is_admin());
-- update はポリシーなし＝不可（付け替えは delete ＋ insert）

-- ---- revisions ----
-- 表示中の用語の履歴は誰でも読める。管理者はすべて読める
-- 書き込みはトリガーと RPC（security definer）だけ
create policy revisions_select on public.revisions
  for select using (
    is_admin() or exists (select 1 from public.terms t where t.id = term_id)
  );

-- ---- reports ----
create policy reports_insert on public.reports
  for insert with check (auth.uid() is not null and reporter = auth.uid());
create policy reports_select on public.reports
  for select using (reporter = auth.uid() or is_admin());
create policy reports_admin on public.reports
  for update using (is_admin()) with check (is_admin());

-- =====================================================================
-- RPC（クライアントから supabase.rpc('名前', {...}) で呼ぶ）
-- =====================================================================

-- 18歳以上の確認
create or replace function public.confirm_adult()
returns void language plpgsql security definer set search_path = public as $$
begin
  if auth.uid() is null then raise exception 'ログインが必要です'; end if;
  update profiles set adult_confirmed_at = now()
  where id = auth.uid() and adult_confirmed_at is null;
end $$;

-- 用語の削除（論理削除）。関係線は残り、差し戻しで用語ごと戻る
create or replace function public.soft_delete_term(p_term_id bigint)
returns void language plpgsql security definer set search_path = public as $$
begin
  if not (can_edit() or is_admin()) then raise exception '編集権限がありません'; end if;
  update terms set deleted_at = now()
  where id = p_term_id and deleted_at is null and (not is_hidden or is_admin());
  if not found then raise exception '用語が見つかりません'; end if;
end $$;

-- 管理者による差し戻し（指定した履歴1件の変更を打ち消す）
-- 差し戻し自体も source = 'revert' として履歴に残る
create or replace function public.revert_revision(p_revision_id bigint)
returns void language plpgsql security definer set search_path = public as $$
declare
  r revisions;
begin
  if not is_admin() then raise exception '管理者のみ実行できます'; end if;

  select * into r from revisions where id = p_revision_id for update;
  if not found then raise exception '履歴が見つかりません'; end if;
  if r.reverted_at is not null then raise exception 'この履歴は差し戻し済みです'; end if;

  perform set_config('app.source', 'revert', true);

  if r.table_name = 'terms' then
    if r.op = 'INSERT' then
      update terms set deleted_at = now() where id = r.term_id;
    elsif r.op = 'UPDATE' then
      update terms set
        label       = r.old_data->>'label',
        description = r.old_data->>'description',
        is_hidden   = (r.old_data->>'is_hidden')::boolean,
        deleted_at  = (r.old_data->>'deleted_at')::timestamptz
      where id = r.term_id;
    else  -- DELETE（管理者による完全削除）を戻す
      insert into terms select * from jsonb_populate_record(null::terms, r.old_data);
    end if;
  else
    if r.op = 'INSERT' then
      delete from term_parents where child_id = r.term_id and parent_id = r.parent_id;
    else  -- DELETE を戻す
      insert into term_parents
      select * from jsonb_populate_record(null::term_parents, r.old_data)
      on conflict do nothing;
    end if;
  end if;

  update revisions set reverted_at = now(), reverted_by = auth.uid() where id = p_revision_id;
  perform set_config('app.source', '', true);
end $$;

-- 利用者を編集禁止にする／解除する
create or replace function public.set_banned(p_user_id uuid, p_banned boolean)
returns void language plpgsql security definer set search_path = public as $$
begin
  if not is_admin() then raise exception '管理者のみ実行できます'; end if;
  update profiles set is_banned = p_banned where id = p_user_id;
end $$;

-- 内部用の関数はクライアントから直接呼べないようにする
revoke execute on function public.handle_new_user()            from anon, authenticated, public;
revoke execute on function public.profiles_guard()             from anon, authenticated, public;
revoke execute on function public.terms_before_write()         from anon, authenticated, public;
revoke execute on function public.term_parents_prevent_cycle() from anon, authenticated, public;
revoke execute on function public.log_revision()               from anon, authenticated, public;

-- 画面から呼ぶ関数は、ログインした人だけが呼べるようにする
-- （is_admin / can_edit / is_privileged は RLS の判定に使うので誰でも呼べるままにする）
revoke execute on function public.confirm_adult()         from anon, public;
revoke execute on function public.soft_delete_term(bigint) from anon, public;
revoke execute on function public.revert_revision(bigint)  from anon, public;
revoke execute on function public.set_banned(uuid, boolean) from anon, public;
grant  execute on function public.confirm_adult()         to authenticated;
grant  execute on function public.soft_delete_term(bigint) to authenticated;
grant  execute on function public.revert_revision(bigint)  to authenticated;
grant  execute on function public.set_banned(uuid, boolean) to authenticated;

